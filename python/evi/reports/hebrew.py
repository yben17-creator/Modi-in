def solvency_text(r: Result) -> str:
    m, cd = r.m, r.cd
    nd, ndE, cov, cr = v(m["net_debt"]), v(m["nd_ebitda"]), v(m["coverage"]), v(m["current_ratio"])
    parts = []
    if nd is None:
        parts.append("לא ניתן לחשב את החוב הנטו בגלל נתוני מאזן חסרים.")
    elif nd <= 0:
        parts.append(f"לחברה מזומן נטו של {money(-nd)}, כך שהחוב ({money(m['total_debt'])}) מכוסה במלואו ביתרות הנזילות.")
    else:
        parts.append(f"לחברה חוב נטו של {money(nd)}" + (f", כ-{ndE:.1f} פעמים ה-EBITDA השנתי." if ndE and 0 < ndE < 1e6 else ", בעוד ה-EBITDA שלילי או לא זמין."))
    opi = v(cd.f("operating_income"))
    if cov == float("inf"):
        parts.append("אין הוצאות ריבית מהותיות.")
    elif cov is not None:
        parts.append(f"הרווח התפעולי מכסה את הוצאות הריבית פי {cov:.1f}." if opi and opi > 0 else
                     "הרווח התפעולי שלילי ולכן אינו מכסה את הריבית; הפירעון תלוי ביתרות המזומן ובמימון חיצוני.")
    else:
        parts.append("הוצאות הריבית לא דווחו בתגי XBRL — כיסוי הריבית חסר.")
    parts.append(f"היחס השוטף עומד על {cr:.2f}." if cr is not None else "היחס השוטף חסר.")
    conv = cd.f("convertible_debt")
    if conv:
        parts.append(f"{money(conv)} מהחוב הם אג\"ח להמרה — מקור דילול פוטנציאלי.")
    if r.near_maturities:
        ca = v(m["cash_all"]) or 0
        parts.append(f"פירעונות של {money(r.near_maturities)} בשנה-שנתיים הקרובות " +
                     ("עולים על המזומן והתזרים — סיכון מימון מחדש מהותי." if r.near_maturities > ca + max(v(m['fcf']) or 0, 0) else "מכוסים במזומן הקיים."))
    elif not cd.maturities:
        parts.append("לוח פירעונות החוב לא דווח ב-XBRL.")
    return " ".join(parts)


def earnings_text(r: Result) -> str:
    cd, e = r.cd, r.e
    s = cd.surprises
    out = []
    if s:
        beats = sum(1 for x in s if x["actual"] > x["estimate"])
        sp = [x["surprise_pct"] for x in s if x.get("surprise_pct") is not None]
        out.append(f"החברה עקפה את תחזית ה-EPS ב-{beats} מתוך {len(s)} הרבעונים הזמינים" + (f", בהפתעה ממוצעת של {sum(sp) / len(sp):.1f}%." if sp else "."))
        if len(s) < 8:
            out.append(f"זמינים {len(s)} רבעונים בלבד (פחות משמונה) — המסקנה חלקית.")
    else:
        out.append("היסטוריית הפתעות EPS אינה זמינה (דורש מפתח Finnhub).")
    if r.rev_change is not None:
        out.append(f"הקונצנזוס ל-EPS השתנה ב-{r.rev_change:+.1%} בתקופת המעקב — " + ("מגמה תומכת שמעלה גם את הרף." if r.rev_change > 0.02 else "הרף נמוך יותר, אך המגמה העסקית שלילית." if r.rev_change < -0.02 else "יציבות יחסית."))
    else:
        out.append("כיוון עדכוני האנליסטים עדיין לא ידוע: המערכת אוספת צילומי קונצנזוס בכל סריקה ותציג מגמה לאחר 30 יום.")
    r3 = v(r.m["ret3m"])
    if r3 is not None:
        out.append(f"המניה עלתה {r3:.0%} בשלושה חודשים, כך שחלק מהציפיות כנראה כבר מגולם במחיר." if r3 > 0.1 else
                   f"המניה ירדה {abs(r3):.0%} בשלושה חודשים — הציפיות נמוכות יחסית." if r3 < 0 else "")
    g = cd.manual.get("guidance")
    out.append({"raised": "לפי הזנה ידנית, ההנהלה העלתה תחזית.", "maintained": "לפי הזנה ידנית, ההנהלה שמרה על התחזית.",
                "lowered": "לפי הזנה ידנית, ההנהלה הורידה תחזית."}.get(g, "תחזית ההנהלה לא הוזנה."))
    mos = r.val.get("mos")
    if mos is not None:
        out.append("בהינתן פער בין המחיר לשווי הבסיס, דוח חיובי עשוי לשמש קטליזטור להערכה מחודשת — השערה, לא תחזית." if mos > 0.15 else
                   "מאחר שהמחיר אינו נמוך משמעותית משווי הבסיס, פוטנציאל ההערכה המחודשת סביב הדוח מוגבל.")
    out.append("דוח טוב אינו מבטיח עלייה במחיר המניה.")
    return " ".join(x for x in out if x)


def dilution_text(r: Result) -> str:
    cd, m = r.cd, r.m
    p = []
    d = cd.dilution
    if d.get("has_recent_offering"):
        p.append("הוגש תשקיף הנפקה (424B) ב-12 החודשים האחרונים — הנפקה בפועל או תוכנית ATM; יש לעיין במסמך")
    elif d.get("has_shelf"):
        p.append("קיימת מסגרת Shelf (S-3) — מסגרת בלבד, לא הנפקה שהוכרזה")
    if cd.f("convertible_debt"):
        p.append("אג\"ח להמרה עשוי לדלל אם המחיר יעלה מעל מחיר ההמרה")
    sp = v(m["sbc_pct"])
    if sp is not None and sp > 0.15:
        p.append(f"SBC גבוה ({sp:.0%} מההכנסות)")
    dr = v(m["dilution_rate"])
    if dr is not None:
        p.append(f"מספר המניות משתנה בקצב שנתי של {dr:+.1%}")
    if cd.f("buyback_remaining"):
        p.append(f"יתרת תוכנית רכישה עצמית {money(cd.f('buyback_remaining'))}")
    return "; ".join(p) or "לא זוהו מקורות דילול מהותיים בנתונים הזמינים"


def final_reason(r: Result) -> str:
    fin, h, val = r.fin, r.h, r.val
    if fin["idx"] in (3, 4):
        return fin.get("reason", "")
    s = f"הציון המשוקלל {fin['composite']:.0f} (35% בריאות, 35% תמחור, 20% הזדמנות דוח, 10% היפוך סיכון)."
    if fin.get("missing_parts"):
        s += " רכיבים שלא חושבו בגלל נתונים חסרים נספרו כציון ניטרלי 50 (לא הוצאו מהשקלול)."
    if fin["idx"] == 0:
        s += f" שילוב של איתנות פיננסית ({h.score:.0f}), מרווח ביטחון של {pct(val.get('mos'), 0)} וסיכון מתון מצדיק מחקר מעמיק — לא החלטת השקעה."
    elif fin["idx"] == 1:
        s += f" הדירוג הוגבל: {fin['reason']}." if fin["capped"] else " החברה עומדת בתנאי האיכות, אך מרווח הביטחון, הסיכון או ההזדמנות אינם מספיקים לעדיפות גבוהה."
    else:
        s += " האותות מעורבים ואין ביסוס מספיק להמשך מחקר בעדיפות."
    return s


def sections(r: Result) -> list[tuple[str, str, str]]:
    cd, m, val, h = r.cd, r.m, r.val, r.h
    rev, g = v(m["revenue"]), v(m["rev_growth_1y"])
    ni, om, omp = v(cd.f("net_income")), v(m["op_margin"]), v(m["op_margin_prev"])
    overview = (f"{cd.name} ({cd.ticker}) נסחרת ב-{cd.exchange or NA} ומסווגת לסקטור {cd.sector or NA} "
                f"({cd.sources_used.get('סיווג סקטור', '')}). תיאור פעילות לפי SEC: {cd.sic_desc or NA}. "
                "תיאור המוצרים והיתרון התחרותי אינו זמין כנתון מובנה — יש להשלים מדוח 10-K (סעיף Business). "
                + (f"הערת חוקר: {cd.manual['moat']}" if cd.manual.get("moat") else ""))
    fin = []
    if rev is not None:
        fin.append(f"החברה מכניסה כ-{money(rev)} ב-12 החודשים האחרונים" + (f", {'צמיחה' if g >= 0 else 'ירידה'} של {abs(g):.1%} לעומת השנה הקודמת" if g is not None else "")
                   + (f" ו-CAGR של {pct(m['rev_cagr_3y'])} בשלוש שנים." if m["rev_cagr_3y"] else "."))
    else:
        fin.append("נתוני ההכנסות חסרים.")
    if ni is not None:
        fin.append((f"היא רווחית, עם רווח נקי של {money(ni)}" if ni > 0 else f"היא מפסידה: הפסד נקי של {money(-ni)}") +
                   (f" ומרווח תפעולי של {pct(om)}" if om is not None else "") +
                   (f" (לעומת {pct(omp)} בתקופה המקבילה)." if omp is not None else "."))
    fin.append(f"בקופה {money(m['cash_all'])} במזומן והשקעות קצרות מול חוב של {money(m['total_debt'])}. {solvency_text(r)}")
    fcf, sbc = v(m["fcf"]), v(cd.f("sbc"))
    if fcf is not None:
        t = f"התזרים החופשי עומד על {money(fcf)} (מרווח {pct(m['fcf_margin'])})."
        if sbc is not None:
            t += (f" <b>חשוב:</b> תגמול מבוסס מניות של {money(sbc)} מהווה {sbc / fcf:.0%} מה-FCF — לאחר ניכויו נותר {money(m['adj_fcf'])}."
                  if fcf > 0 and sbc / fcf > 0.5 else f" לאחר ניכוי תגמול מבוסס מניות ({money(sbc)}) נותר {money(m['adj_fcf'])}.")
        fin.append(t)
    else:
        fin.append("התזרים החופשי אינו ניתן לחישוב (תזרים מפעילות או CapEx חסרים).")
    fin.append(f"ציון הבריאות הפיננסית: {h.score:.0f}/100 (כיסוי נתונים {h.coverage:.0%})." if h.score is not None else f"ציון הבריאות לא חושב: {'; '.join(h.notes)}")
    if r.severe:
        fin.append(f"<b>מסומנת כבעלת סיכון פיננסי חמור: {'; '.join(r.severe)}.</b>")
    vt = []
    if val.get("mid") is not None:
        vt.append(f"שווי השוק {money(m['mcap'])} (EV של {money(m['ev'])}). מודל ה-DCF מעריך טווח שווי בין {price(val['low'])} ל-{price(val['high'])} למניה, "
                  f"עם תרחיש בסיס של {price(val['mid'])}, לעומת מחיר של {price(cd.price)}.")
        mos = val.get("mos")
        if mos is not None:
            vt.append(f"המחיר נמוך בכ-{mos:.0%} משווי הבסיס — מרווח ביטחון משמעותי." if mos >= .15 else
                      f"מרווח הביטחון מצומצם ({mos:.0%})." if mos > 0 else "המחיר גבוה משווי הבסיס — השוק מתמחר צמיחה או רווחיות גבוהות מהנחות הבסיס.")
        vt.append(val.get("reliability_note", ""))
    else:
        vt.append(val.get("dcf_missing", "DCF לא חושב."))
    rd, hd = val.get("rel_disc"), val.get("hist_disc")
    vt.append(f"במכפילים: EV/Revenue {_m(m['ev_rev'])}, EV/FCF {_m(m['ev_fcf'])}, P/E {_m(m['pe'])}. " +
              (f"{'הנחה' if rd > 0 else 'פרמיה'} של כ-{abs(rd):.0%} לחציון העמיתים שנסרקו. " if rd is not None else "אין מספיק עמיתים מאותו סקטור בסריקה להשוואה. ") +
              (f"{'הנחה' if hd > 0 else 'פרמיה'} של כ-{abs(hd):.0%} למכפילים ההיסטוריים של החברה." if hd is not None else "מכפילים היסטוריים אינם זמינים."))
    if val.get("damp", 1) < 1:
        vt.append("מאחר שהצמיחה נמוכה או שקיים דגל מבני, משקל המכפילים הנמוכים הופחת — ייתכן שהם משקפים הרעה אמיתית.")
    if r.fa.get("cls") not in ("לא רלוונטי", "לא ניתן לחשב"):
        vt.append(f"סיווג Fallen Angel: <b>{r.fa['cls']}</b> — {'; '.join(r.fa['why'])}.")
    if val.get("upside") is not None:
        vt.append(f"פוטנציאל העלייה לשווי הכלכלי ({val['upside']:+.0%}) הוא אופק ארוך-טווח ונפרד מהתשואה האפשרית סביב הדוח הקרוב.")
    ne = cd.next_earnings or {}
    if ne.get("date"):
        hour = {"amc": "אחרי המסחר", "bmo": "לפני המסחר"}.get((ne.get("hour") or "").lower(), "שעה לא ידועה")
        cat = (f"הדוח הבא: {ne['date']} ({hour}) — סטטוס: {DATE_STATUS.get(ne.get('status'), ne.get('status'))}. "
               + (f"הקונצנזוס: EPS {price(ne.get('eps_est'))}, הכנסות {money(ne.get('rev_est'))}. " if ne.get("eps_est") is not None else "קונצנזוס האנליסטים אינו זמין. ")
               + earnings_text(r))
    else:
        cat = "מועד הדוח הבא אינו ידוע. " + earnings_text(r)
    if r.mon.get("available") and r.mon.get("alerts"):
        cat += " התראות מומנטום: " + ", ".join(a["he"] for a in r.mon["alerts"]) + "."
    fl = [f"{f.title} ({f.status}, חומרה {SEV[f.severity]}, {'ידוע לשוק' if f.known else 'מידע חדש'}, {f.date}) — {f.impact}" for f in cd.flags]
    flags = f"ציון הסיכון {r.r['score']:.0f}/100. " + (" ".join(fl) if fl else "לא אותרו דגלים אדומים במקורות שנבדקו (" + ", ".join(r.r["checked"]) + "). ")
    flags += f" דילול: {dilution_text(r)}."
    if r.r["unusual"]:
        flags += " נרשמו מכירות חריגות של בעלי עניין מחוץ לתוכנית מתוכננת (" + ", ".join(f"{t.who} {money(t.value)}" for t in r.r["unusual"][:4]) + ") — מצדיק בירור אך אינו בהכרח סימן שלילי."
    if r.r["override"]:
        flags += f" <b>{r.r['override']['reason']}.</b>"
    t = r.t
    if not t.get("available"):
        ent = f"ניתוח חלונות ההחזקה אינו זמין: {t.get('why')}."
    elif t["n"] < 8:
        ent = f"קיימים רק {t['n']} דוחות היסטוריים עם נתוני מחיר — אין מספיק נתונים להשוואה אמינה בין חלונות החזקה."
    else:
        b = best_window(t)
        ent = (f"בבדיקה היסטורית על {t['n']} דוחות אמיתיים (מועדי 8-K ומחירי {t['price_source']}), "
               + (f"החלון \"{b['label']}\" הציג את יחס התשואה/סיכון הגבוה ביותר (ממוצע {b['avg']:+.2%}, Win Rate {b['win']:.0%}, רמת ביטחון {b['conf']}). " if b else "לא נמצא חלון עדיף. ")
               + "תצפיות עבר אינן תחזית. יש לבחון מחדש החזקה אם התחזית מונמכת, אם המניה שוברת את ממוצע 50 יום, או אם המחיר מתקרב לשווי הבסיס.")
    final = f"<b>{r.fin['cls']}.</b> {final_reason(r)}"
    return [("סקירת החברה", "Company Overview", overview), ("מצב פיננסי", "Financial Position", " ".join(fin)),
            ("הערכת שווי", "Valuation Assessment", " ".join(x for x in vt if x)), ("קטליזטור הדוח", "Earnings Catalyst", cat),
            ("דגלים אדומים", "Red Flags", flags), ("תרחישי כניסה ויציאה", "Entry & Exit Scenarios", ent),
            ("הערכה סופית", "Final Assessment", final)]


def _m(x) -> str:
    from ..fmt import mult
    return mult(x)
